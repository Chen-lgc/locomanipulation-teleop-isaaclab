#!/usr/bin/env python3
"""Check full-vs-reduced PiperX FK, then run one small Mink IK displacement.

Uses no viewer and does not start Isaac Sim. Run in pixi humble where
`mujoco`, `mink`, `daqp` and `numpy` are available.
"""

from __future__ import annotations

from pathlib import Path
import sys

import mujoco
import numpy as np

PROJECT = Path(__file__).resolve().parents[1]
COMPLETE = PROJECT / "robot_model" / "a2_piper_x.xml"
REDUCED = PROJECT / "robot_model" / "scene_floating_piperx.xml"
JOINTS = tuple(f"joint{i}" for i in range(1, 9))


def qadr(m, name):
    return int(m.jnt_qposadr[m.joint(name).id])


def scene_site_in_base(m, d):
    base_id = m.body("base").id
    site_id = m.site("attachment_site").id
    R_base = d.xmat[base_id].reshape((3, 3))
    R_ee = d.site_xmat[site_id].reshape((3, 3))
    p = R_base.T @ (d.site_xpos[site_id] - d.xpos[base_id])
    R = R_base.T @ R_ee
    return p, R


def main():
    full = mujoco.MjModel.from_xml_path(str(COMPLETE))
    lite = mujoco.MjModel.from_xml_path(str(REDUCED))
    print(f"Full: nq={full.nq} nv={full.nv} nu={full.nu}")
    print(f"IK:   nq={lite.nq} nv={lite.nv} nu={lite.nu}")
    if (lite.nq, lite.nv) != (10, 10):
        raise AssertionError("Reduced IK model must have 2 virtual DOFs + 6 joints + 2 fingers")
    m = [mujoco.mj_id2name(lite, mujoco.mjtObj.mjOBJ_JOINT, i) for i in range(lite.njnt)]
    expected = ["basepitch", "basez"] + list(JOINTS)
    if m != expected:
        raise AssertionError(f"Unexpected IK joint order: {m} != {expected}")

    d_full, d_lite = mujoco.MjData(full), mujoco.MjData(lite)
    home_id = mujoco.mj_name2id(full, mujoco.mjtObj.mjOBJ_KEY, "home")
    rng = np.random.default_rng(17)
    pos_err = []
    rot_err = []
    for case in range(6):
        d_full.qpos[:] = full.key_qpos[home_id] if home_id >= 0 else full.qpos0
        d_lite.qpos[:] = lite.qpos0
        # Test different random valid arm poses. Only the six joint angles vary;
        # finger positions are copied from the full model and remain coupled.
        for name in JOINTS:
            jid = full.joint(name).id
            lo, hi = full.jnt_range[jid]
            orig = float(d_full.qpos[qadr(full, name)])
            if case and name in JOINTS[:6]:
                candidate = orig + rng.uniform(-0.15, 0.15)
                value = float(np.clip(candidate, lo + 1e-5, hi - 1e-5))
            else:
                value = orig
            d_full.qpos[qadr(full, name)] = value
            d_lite.qpos[qadr(lite, name)] = value
        # Keep the base upright; the full model's world translation is irrelevant.
        d_full.qpos[3:7] = [1, 0, 0, 0]
        mujoco.mj_forward(full, d_full)
        mujoco.mj_forward(lite, d_lite)
        p0, R0 = scene_site_in_base(full, d_full)
        p1, R1 = scene_site_in_base(lite, d_lite)
        pe = np.linalg.norm(p0 - p1)
        re = np.linalg.norm(R0 - R1, ord="fro")
        pos_err.append(pe)
        rot_err.append(re)
        print(f"FK case={case}: position difference={pe:.3e} m; rotation matrix diff={re:.3e}")

    if max(pos_err) > 1e-5 or max(rot_err) > 1e-5:
        raise AssertionError("FK MISMATCH: check arm mounting transform, joint axes and attachment_site")
    print("FULL vs REDUCED FK: PASS")

    # The reduced model can already be used as a geometry-only FK check even
    # if Mink is unavailable. The following confirms the IK control chain too.
    sys.path.insert(0, str(PROJECT / "deploy"))
    from ik_mink_piperx import IKMink

    ik = IKMink()
    initial_arm = np.array([float(d_full.qpos[qadr(full, n)]) for n in JOINTS[:6]])
    d_lite.qpos[:] = lite.qpos0
    for name, angle in zip(JOINTS[:6], initial_arm):
        d_lite.qpos[qadr(lite, name)] = angle
    mujoco.mj_forward(lite, d_lite)
    p_initial, _ = scene_site_in_base(lite, d_lite)

    # A *known-reachable* target is generated by forward-kinematics of a
    # nearby valid shoulder joint configuration. Arbitrary Cartesian offsets
    # can lie outside the workspace, so they are unsuitable for a smoke test.
    q_goal = initial_arm.copy()
    joint2_id = lite.joint("joint2").id
    low, high = lite.jnt_range[joint2_id]
    delta = 0.12 if q_goal[1] + 0.12 < high else -0.12
    q_goal[1] = float(np.clip(q_goal[1] + delta, low + 1e-4, high - 1e-4))
    for name, angle in zip(JOINTS[:6], q_goal):
        d_lite.qpos[qadr(lite, name)] = angle
    mujoco.mj_forward(lite, d_lite)
    target, _ = scene_site_in_base(lite, d_lite)
    print(f"Known-reachable target displacement: {np.linalg.norm(target - p_initial):.4f} m")
    base, arm, ok = ik.compute(target, np.array([1., 0., 0., 0.]), initial_arm, np.zeros(2))
    d_lite.qpos[:] = lite.qpos0
    for name, v in zip(["basepitch", "basez"] + list(JOINTS[:6]), np.r_[base, arm]):
        d_lite.qpos[qadr(lite, name)] = v
    mujoco.mj_forward(lite, d_lite)
    actual, _ = scene_site_in_base(lite, d_lite)
    diff = float(np.linalg.norm(actual - target))
    print(f"IK target xyz: {target.round(4)}")
    print(f"IK result xyz: {actual.round(4)}")
    print(f"IK error: {diff:.4f} m; solver_success={ok}")
    if not ok or diff > 0.02:
        raise AssertionError("IK test did not reach 2 cm tolerance; try a different reachable pose")
    print("PIPERX MINK IK: PASS")


if __name__ == "__main__":
    main()
